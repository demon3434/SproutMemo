export const defaultTheme = themeList.find(t => t.id === 18); // 默认“极极简纯白”为系统默认主题

export function applyTheme(themeId) {
  let theme = themeList.find(t => t.id === Number(themeId));
  if (!theme) {
    // 兼容之前只存了 mode 的旧情况
    const mode = localStorage.getItem('theme-mode') || 'light';
    if (mode === 'dark') {
      theme = themeList.find(t => t.id === 8); // 星空夜幕
    } else {
      theme = themeList.find(t => t.id === 18); // 极简纯白
    }
  }
  
  if (!theme) theme = defaultTheme;

  const root = document.documentElement;
  root.style.setProperty('--primary', theme.neonBlue);
  root.style.setProperty('--primary-hover', theme.neonBlue);
  root.style.setProperty('--primary-light', theme.neonBlue + '1A'); // 1A 代表 10% 透明度十六进制
  root.style.setProperty('--bg-main', theme.darkBg);
  root.style.setProperty('--bg-card', theme.cardBg);
  root.style.setProperty('--bg-input', theme.isDark ? theme.darkBg : '#f8fafc');
  root.style.setProperty('--text-main', theme.textPrimary);
  root.style.setProperty('--text-muted', theme.textSecondary);
  
  // 调整边框颜色和侧边栏颜色以匹配亮色/暗色
  if (theme.isDark) {
    root.style.setProperty('--border', 'rgba(255, 255, 255, 0.08)');
    root.style.setProperty('--bg-sidebar', theme.darkBg === '#15151A' ? '#0a0a0d' : '#050508');
    root.style.setProperty('--text-sidebar', '#94a3b8');
    root.style.setProperty('--text-sidebar-hover', '#ffffff');
    root.style.setProperty('--bg-sidebar-hover', 'rgba(255, 255, 255, 0.06)');
  } else {
    // 亮色主题：菜单栏背景色设为亮色
    root.style.setProperty('--border', 'rgba(0, 0, 0, 0.08)');
    root.style.setProperty('--bg-sidebar', '#ffffff'); // 亮色菜单栏背景
    root.style.setProperty('--text-sidebar', '#64748b'); // 菜单文字灰色
    root.style.setProperty('--text-sidebar-hover', theme.neonBlue); // hover时使用主题高亮
    root.style.setProperty('--bg-sidebar-hover', 'rgba(0, 0, 0, 0.04)'); // hover底色
  }

  // 绑定全局暗色类
  document.body.classList.toggle('dark-mode', theme.isDark);
}
